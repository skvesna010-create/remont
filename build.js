/* Сборка страниц из content.json: node build.js */
const fs = require('fs'), T = require('./tpl.js');
const C = JSON.parse(fs.readFileSync(__dirname + '/content.json', 'utf8'));
fs.writeFileSync(__dirname + '/index.html', T.pageS(C));
fs.mkdirSync(__dirname + '/s', { recursive:true });
fs.writeFileSync(__dirname + '/s/index.html', T.pageS(C).replace('<head>', '<head><meta name="robots" content="noindex">'));
fs.mkdirSync(__dirname + '/m', { recursive:true });
fs.writeFileSync(__dirname + '/m/index.html', T.pageM(C));
fs.writeFileSync(__dirname + '/sitemap.xml', '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n<url><loc>https://remont.domilia.ru/</loc><lastmod>' + new Date().toISOString().slice(0, 10) + '</lastmod></url>\n<url><loc>https://remont.domilia.ru/vannaya/</loc></url>\n</urlset>\n');
fs.mkdirSync(__dirname + '/c', { recursive:true });
fs.writeFileSync(__dirname + '/c/index.html', T.pageC(C).replace('<head>', '<head><meta name="robots" content="noindex">'));
fs.mkdirSync(__dirname + '/a', { recursive:true });
fs.writeFileSync(__dirname + '/a/index.html', T.page(C).replace('<head>', '<head><meta name="robots" content="noindex">').replace(/<script>\(function\(\)\{try\{if\(\/\[\?&\]ab=a[\s\S]*?<\/script>/, ''));
fs.mkdirSync(__dirname + '/v2', { recursive:true });
fs.writeFileSync(__dirname + '/v2/index.html', T.pageB(C));
fs.mkdirSync(__dirname + '/kviz', { recursive:true });
fs.writeFileSync(__dirname + '/kviz/index.html', T.quizPage(C));
fs.mkdirSync(__dirname + '/vannaya', { recursive:true });
fs.writeFileSync(__dirname + '/vannaya/index.html', T.pageS(C, true));
fs.mkdirSync(__dirname + '/vannaya-old', { recursive:true });
fs.writeFileSync(__dirname + '/vannaya-old/index.html', T.pageBath(C).replace('<head>', '<head><meta name="robots" content="noindex">'));
fs.mkdirSync(__dirname + '/spasibo', { recursive:true });
fs.writeFileSync(__dirname + '/spasibo/index.html', T.thanks(C));
fs.writeFileSync(__dirname + '/404.html', T.notFound(C));
console.log('готово: index.html, spasibo/index.html, 404.html');
